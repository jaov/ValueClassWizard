package dev.j8a.valuewizard;

import com.sun.source.tree.ClassTree;
import com.sun.source.tree.MethodTree;
import com.sun.source.tree.Tree;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.VariableElement;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.ElementFilter;
import javax.lang.model.util.Types;
import org.netbeans.api.java.source.CompilationInfo;

/**
 * Recognizes the staged builder generated by this module and compares it with
 * the current fields of the value class.
 */
final class GeneratedBuilder {

    private static final String BUILDER = CodeGeneratorSupport.BUILDER_NAME;
    private static final String CAN_BUILD = CodeGeneratorSupport.CAN_BUILD_NAME;

    final TypeElement builderType;
    final TypeElement canBuildType;
    final List<TypeElement> stageTypes;
    final List<VariableElement> builderFields;

    private GeneratedBuilder(TypeElement builderType, TypeElement canBuildType,
            List<TypeElement> stageTypes, List<VariableElement> builderFields) {
        this.builderType = builderType;
        this.canBuildType = canBuildType;
        this.stageTypes = stageTypes;
        this.builderFields = builderFields;
    }

    static GeneratedBuilder find(CompilationInfo info, TypeElement type) {
        if (type.getKind() != ElementKind.CLASS) {
            return null;
        }
        Types types = info.getTypes();

        TypeElement builderType = null;
        TypeElement canBuildType = null;
        for (TypeElement nested : ElementFilter.typesIn(type.getEnclosedElements())) {
            if (nested.getSimpleName().contentEquals(BUILDER)
                    && nested.getKind() == ElementKind.CLASS) {
                builderType = nested;
            } else if (nested.getSimpleName().contentEquals(CAN_BUILD)
                    && nested.getKind() == ElementKind.INTERFACE) {
                canBuildType = nested;
            }
        }
        if (builderType == null || canBuildType == null) {
            return null;
        }
        if (!builderType.getModifiers().containsAll(
                java.util.EnumSet.of(Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL))) {
            return null;
        }
        if (!canBuildType.getModifiers().contains(Modifier.PUBLIC)) {
            return null;
        }

        ExecutableElement builderMethod = null;
        for (ExecutableElement method : ElementFilter.methodsIn(type.getEnclosedElements())) {
            if (method.getSimpleName().contentEquals("builder")
                    && method.getParameters().isEmpty()
                    && method.getModifiers().containsAll(
                            java.util.EnumSet.of(Modifier.PUBLIC, Modifier.STATIC))) {
                if (builderMethod != null) {
                    return null;
                }
                builderMethod = method;
            }
        }
        if (builderMethod == null) {
            return null;
        }

        TypeElement firstStage = asTypeElement(types, builderMethod.getReturnType());
        if (firstStage == null || !isStageInterface(firstStage, type)) {
            return null;
        }

        List<TypeElement> implementedStages = new ArrayList<>();
        boolean implementsCanBuild = false;
        for (TypeMirror implemented : builderType.getInterfaces()) {
            TypeElement implementedType = asTypeElement(types, implemented);
            if (implementedType == null) {
                return null;
            }
            if (implementedType.getSimpleName().contentEquals(CAN_BUILD)) {
                if (!sameType(implementedType, canBuildType, types)) {
                    return null;
                }
                implementsCanBuild = true;
            } else if (isStageInterface(implementedType, type)) {
                implementedStages.add(implementedType);
            } else {
                return null;
            }
        }
        if (!implementsCanBuild || implementedStages.isEmpty()) {
            return null;
        }

        List<TypeElement> chain = validateChain(info, type, firstStage, canBuildType);
        if (chain == null || chain.size() != implementedStages.size()) {
            return null;
        }
        Set<String> implementedNames = new HashSet<>();
        for (TypeElement stage : implementedStages) {
            implementedNames.add(stage.getQualifiedName().toString());
        }
        for (TypeElement stage : chain) {
            if (!implementedNames.remove(stage.getQualifiedName().toString())) {
                return null;
            }
        }
        if (!implementedNames.isEmpty()) {
            return null;
        }

        List<VariableElement> fields = new ArrayList<>();
        for (VariableElement field : ElementFilter.fieldsIn(builderType.getEnclosedElements())) {
            if (!field.getModifiers().contains(Modifier.PRIVATE)
                    || field.getModifiers().contains(Modifier.STATIC)) {
                return null;
            }
            fields.add(field);
        }
        if (fields.isEmpty()) {
            return null;
        }
        if (chain.size() != fields.size()) {
            return null;
        }

        List<ExecutableElement> constructors
                = ElementFilter.constructorsIn(builderType.getEnclosedElements());
        if (constructors.size() != 1) {
            return null;
        }
        ExecutableElement constructor = constructors.get(0);
        if (!constructor.getParameters().isEmpty()
                || !constructor.getModifiers().contains(Modifier.PRIVATE)) {
            return null;
        }

        List<ExecutableElement> setters = new ArrayList<>();
        ExecutableElement buildMethod = null;
        for (ExecutableElement method : ElementFilter.methodsIn(builderType.getEnclosedElements())) {
            String name = method.getSimpleName().toString();
            if ("build".equals(name) && method.getParameters().isEmpty()) {
                if (buildMethod != null) {
                    return null;
                }
                buildMethod = method;
            } else if (name.startsWith("set") && method.getParameters().size() == 1) {
                setters.add(method);
            } else {
                return null;
            }
        }
        if (buildMethod == null || setters.size() != fields.size()) {
            return null;
        }
        if (!types.isSameType(buildMethod.getReturnType(), type.asType())) {
            return null;
        }

        Set<String> expectedSetters = new HashSet<>();
        for (VariableElement field : fields) {
            if (!field.getModifiers().contains(Modifier.PRIVATE)) {
                return null;
            }
            expectedSetters.add(BuilderAst.setterName(field.getSimpleName().toString()));
        }
        Set<String> actualSetters = new HashSet<>();
        for (ExecutableElement setter : setters) {
            actualSetters.add(setter.getSimpleName().toString());
        }
        if (!expectedSetters.equals(actualSetters)) {
            return null;
        }
        for (VariableElement field : fields) {
            ExecutableElement setter = findSetter(setters, field, types);
            if (setter == null) {
                return null;
            }
        }

        for (TypeElement stage : chain) {
            List<ExecutableElement> methods = ElementFilter.methodsIn(stage.getEnclosedElements());
            if (methods.size() != 1) {
                return null;
            }
            ExecutableElement setter = methods.get(0);
            VariableElement field = findField(fields, setter, types);
            if (field == null) {
                return null;
            }
        }

        List<ExecutableElement> buildMethods
                = ElementFilter.methodsIn(canBuildType.getEnclosedElements());
        if (buildMethods.size() != 1) {
            return null;
        }
        ExecutableElement canBuildMethod = buildMethods.get(0);
        if (!canBuildMethod.getSimpleName().contentEquals("build")
                || !canBuildMethod.getParameters().isEmpty()
                || !types.isSameType(canBuildMethod.getReturnType(), type.asType())) {
            return null;
        }

        return new GeneratedBuilder(builderType, canBuildType, chain, fields);
    }

    private static List<TypeElement> validateChain(CompilationInfo info, TypeElement outer,
            TypeElement firstStage, TypeElement canBuildType) {
        Types types = info.getTypes();
        List<TypeElement> chain = new ArrayList<>();
        Set<String> seen = new HashSet<>();
        TypeElement current = firstStage;
        while (current != null) {
            String name = current.getQualifiedName().toString();
            if (!seen.add(name)) {
                return null;
            }
            if (current.getSimpleName().contentEquals(CAN_BUILD)) {
                if (!sameType(current, canBuildType, types)) {
                    return null;
                }
                return chain;
            }
            if (!isStageInterface(current, outer)) {
                return null;
            }
            chain.add(current);
            List<ExecutableElement> methods = ElementFilter.methodsIn(current.getEnclosedElements());
            if (methods.size() != 1) {
                return null;
            }
            TypeElement next = asTypeElement(types, methods.get(0).getReturnType());
            if (next == null) {
                return null;
            }
            current = next;
        }
        return null;
    }

    private static ExecutableElement findSetter(List<ExecutableElement> setters,
            VariableElement field, Types types) {
        String expected = BuilderAst.setterName(field.getSimpleName().toString());
        for (ExecutableElement setter : setters) {
            if (setter.getSimpleName().contentEquals(expected)
                    && setter.getParameters().size() == 1
                    && types.isSameType(
                            setter.getParameters().get(0).asType(), field.asType())) {
                return setter;
            }
        }
        return null;
    }

    private static VariableElement findField(List<VariableElement> fields,
            ExecutableElement setter, Types types) {
        if (setter.getParameters().size() != 1) {
            return null;
        }
        String expected = setter.getSimpleName().toString();
        for (VariableElement field : fields) {
            if (expected.contentEquals(
                    BuilderAst.setterName(field.getSimpleName().toString()))
                    && types.isSameType(
                            setter.getParameters().get(0).asType(), field.asType())) {
                return field;
            }
        }
        return null;
    }

    private static boolean isStageInterface(TypeElement candidate, TypeElement outer) {
        if (candidate.getKind() != ElementKind.INTERFACE
                || !candidate.getSimpleName().toString()
                        .startsWith(CodeGeneratorSupport.STAGE_PREFIX)
                || !isDeclaredIn(candidate, outer)
                || !candidate.getModifiers().contains(Modifier.PUBLIC)) {
            return false;
        }
        List<ExecutableElement> methods = ElementFilter.methodsIn(candidate.getEnclosedElements());
        if (methods.size() != 1) {
            return false;
        }
        ExecutableElement method = methods.get(0);
        return method.getSimpleName().toString().startsWith("set")
                && method.getParameters().size() == 1;
    }

    private static boolean isDeclaredIn(TypeElement candidate, TypeElement outer) {
        Element enclosing = candidate.getEnclosingElement();
        return enclosing instanceof TypeElement
                && ((TypeElement) enclosing).getQualifiedName().contentEquals(
                        outer.getQualifiedName());
    }

    private static TypeElement asTypeElement(Types types, TypeMirror mirror) {
        if (mirror == null) {
            return null;
        }
        Element element = types.asElement(mirror);
        return element instanceof TypeElement ? (TypeElement) element : null;
    }

    private static boolean sameType(TypeElement first, TypeElement second, Types types) {
        return types.isSameType(first.asType(), second.asType());
    }

    boolean isStale(List<VariableElement> classFields, Types types) {
        if (classFields.size() != builderFields.size()) {
            return true;
        }
        for (int i = 0; i < classFields.size(); i++) {
            VariableElement current = classFields.get(i);
            VariableElement built = builderFields.get(i);
            if (!current.getSimpleName().contentEquals(built.getSimpleName())) {
                return true;
            }
            if (!types.isSameType(current.asType(), built.asType())) {
                return true;
            }
        }
        return false;
    }

    List<Tree> memberTrees(ClassTree classTree) {
        Set<String> typeNames = new HashSet<>();
        typeNames.add(builderType.getSimpleName().toString());
        typeNames.add(canBuildType.getSimpleName().toString());
        for (TypeElement stage : stageTypes) {
            typeNames.add(stage.getSimpleName().toString());
        }

        List<Tree> result = new ArrayList<>();
        for (Tree member : classTree.getMembers()) {
            if (member instanceof ClassTree) {
                String name = ((ClassTree) member).getSimpleName().toString();
                if (typeNames.contains(name)) {
                    result.add(member);
                }
            } else if (member instanceof MethodTree) {
                MethodTree method = (MethodTree) member;
                if (method.getName().contentEquals("builder")
                        && method.getParameters().isEmpty()) {
                    result.add(member);
                }
            }
        }
        return result;
    }
}
